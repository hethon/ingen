import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import manifestJsonSchema from "../schema/manifest.schema.json";

type JsonSchema = {
  type?: string;
  description?: string;
  properties?: Record<string, JsonSchema>;
  items?: JsonSchema;
  required?: string[];
  enum?: unknown[];
  additionalProperties?: JsonSchema | boolean;
  [key: string]: unknown;
};

type FieldDescription = {
  description?: string;
  required: boolean;
  type: string;
};

type FieldDescriptionMap = Record<string, FieldDescription>;

function getType(node: JsonSchema): string {
  if (node.enum) {
    return node.enum.map((value) => JSON.stringify(value)).join(" | ");
  }

  if (node.type === "array") {
    return node.items ? `${getType(node.items)}[]` : "array";
  }

  if (node.type === "object") {
    if (node.additionalProperties && typeof node.additionalProperties === "object") {
      return `Record<string, ${getType(node.additionalProperties)}>`;
    }

    return "object";
  }

  return node.type ?? "unknown";
}

function getFieldDescriptions(schema: JsonSchema): FieldDescriptionMap {
  const descriptions: FieldDescriptionMap = {};

  function walk(node: JsonSchema, path: string) {
    const required = new Set(node.required ?? []);

    for (const [key, property] of Object.entries(node.properties ?? {})) {
      const propertyPath = path ? `${path}.${key}` : key;

      descriptions[propertyPath] = {
        description: property.description,
        required: required.has(key),
        type: getType(property),
      };

      walk(property, propertyPath);
    }

    if (node.items) {
      walk(node.items, `${path}[]`);
    }
  }

  walk(schema, "");

  return descriptions;
}

function escapeMarkdownTableCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function writeManifestReference(): void {
  const fields = getFieldDescriptions(manifestJsonSchema);
  const outputPath = "docs/manifest_reference.md";
  const rows = Object.entries(fields)
    .filter(([fieldPath]) => fieldPath !== "$schema")
    .map(([fieldPath, field]) => {
      const requirement = field.required ? "Required" : "Optional";
      const description = escapeMarkdownTableCell(`\`[${requirement}]\` ${field.description ?? ""}`);

      const type = escapeMarkdownTableCell(field.type);

      return `| \`${fieldPath}\` | \`${type}\` | ${description} |`;
    })
    .join("\n");

  const markdown = `<!-- Generated by scripts/generate-manifest-reference.ts, do not edit by hand. -->

# Manifest Reference

| Field | Type | Description |
| --- | --- | --- |
${rows}
`;

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, markdown, "utf8");

  console.log(`✓ Manifest reference written to ${outputPath}`);
}

writeManifestReference();
